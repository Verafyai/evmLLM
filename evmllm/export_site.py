"""Export real results (firmware runs, py-evm checks, circuit runs, judge scenarios) to the
static site's data.js. Nothing in data.js is invented: every number comes from a run."""
import glob
import json
import re
import sys
from pathlib import Path

from chipformer.rv import spec as S

from evmllm.demos import ART, DEMOS, describe, jobs
from evmllm.host import run_pyevm, run_ref

SITE = Path(sys.argv[1] if len(sys.argv) > 1 else "../evllm-site")
ROOT = Path(__file__).resolve().parent.parent
src = (ROOT / "contracts" / "Demos.sol").read_text()


def solidity(name):
    i = src.index(f"contract {name} ")
    start = src.rfind("\n\n", 0, i) + 2
    depth, j = 0, src.index("{", i)
    while True:
        depth += {"{": 1, "}": -1}.get(src[j], 0)
        if depth == 0:
            break
        j += 1
    return src[start:j + 1]


def segments(toks, nops):
    """Tokens per EVM opcode: the firmware prints each opcode as two hex BYTE tokens before
    executing it, so BYTE-token positions split the real token stream by EVM step."""
    b = [i for i, t in enumerate(toks) if S.family(int(t))[0] == "BYTE"]
    starts = [b[2 * k] for k in range(nops)] + [len(toks)]
    return starts[0], [starts[k + 1] - starts[k] for k in range(nops)]


circuit = {}
for f in glob.glob(str(ROOT / "results" / "circuit_*.json")):
    for r in json.load(open(f))["runs"]:
        circuit[r["row"]] = r

contracts = {d[1]: {"id": d[0], "name": d[1], "title": d[2], "blurb": d[3], "sig": d[4], "rtype": d[5],
                    "solidity": solidity(d[1]), "runtime": ART[d[1]]["runtime"], "presets": []}
             for d in DEMOS}
explain = None
for row, (did, name, label, sig, rtype, j) in enumerate(jobs()):
    a, b = run_ref(j), run_pyevm(j)
    setup, per = segments(a._toks, len(a.ops))
    p = {"row": row, "label": label, "calldata": j.calldata.hex(),
         "storage": {hex(k): hex(v) for k, v in j.storage.items()},
         "firmware": {"status": a.status, "gas_used": a.gas_used, "ret": a.ret.hex(),
                      "storage": {hex(k): hex(v) for k, v in a.storage.items()},
                      "outcome": describe(a.ret, a.status, rtype), "ops": bytes(a.ops).hex(),
                      "rv_instructions": a.rv_instructions, "tokens": a.tokens,
                      "setup_tokens": setup, "tokens_per_op": per},
         "pyevm": {"status": b.status, "gas_used": b.gas_used, "match": a.key() == b.key()},
         "circuit": circuit.get(row)}
    contracts[name]["presets"].append(p)
    if name == "GCD" and explain is None:
        names = [S.name(int(t)) for t in a._toks]
        explain = {"contract": name, "label": label, "row": row, "setup_tokens": setup,
                   "first_tokens": names[:60],
                   "op_tokens": [names[s:s + n] for s, n in zip(
                       [setup + sum(per[:k]) for k in range(len(per))], per)]}

stats = {
    "fuzz": json.load(open(ROOT / "results" / "fuzz.json"))["pass"],
    "fuzz_n": json.load(open(ROOT / "results" / "fuzz.json"))["n"],
    "demos_ok": sum(p["pyevm"]["match"] for c in contracts.values() for p in c["presets"]),
    "demos_n": sum(len(c["presets"]) for c in contracts.values()),
    "div": json.load(open(ROOT / "results" / "divtest.json"))["pass"],
    "div_n": json.load(open(ROOT / "results" / "divtest.json"))["n"],
    "js_vm": json.load(open(ROOT / "results" / "js_vm.json"))["pass"],
    "js_vm_n": json.load(open(ROOT / "results" / "js_vm.json"))["n"],
    "circuit_runs": len(circuit), "circuit_match": sum(r["match"] for r in circuit.values()),
    "circuit_tokens": sum(r["tokens"] for r in circuit.values() if r["match"]),
}
data = {"contracts": list(contracts.values()), "explain": explain, "stats": stats,
        "judge": json.load(open(ROOT / "results" / "judge.json")),
        "circuit_runs": sorted(circuit.values(), key=lambda r: r["row"])}
(SITE / "data.js").write_text("// Generated by evmllm/export_site.py from real runs. Do not edit by hand.\n"
                              "window.EVMLLM_DATA = " + json.dumps(data, separators=(",", ":")) + ";\n")
print("wrote", SITE / "data.js", stats)
